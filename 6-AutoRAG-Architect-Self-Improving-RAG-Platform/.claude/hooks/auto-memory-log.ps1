# .claude/hooks/auto-memory-log.ps1
# AutoRAG v3.0 — Automatic Session Activity Logger
# Appends a timestamped entry to .claude/SESSION_LOG.md whenever governance
# or spec files are edited. Triggered by Claude Code PostToolUse (Write|Edit)
# -- already registered in .claude/settings.json's hooks.PostToolUse array.
#
# NOTE (24-Jul-2026 audit): this script uses Set-Content/Add-Content for file
# I/O, which CLAUDE.md SS12's Windows Script Encoding Rules says to avoid in
# favor of [System.IO.File]::ReadAllText/WriteAllText -- left as-is since the
# content written here (timestamps, file paths) is ASCII-only in practice, but
# flagging so a future edit that adds non-ASCII content doesn't hit CP1252
# corruption silently.

$ErrorActionPreference = "Continue"

$root    = Split-Path $PSScriptRoot -Parent | Split-Path -Parent
$logFile = Join-Path $PSScriptRoot "..\SESSION_LOG.md"
$logFile = [System.IO.Path]::GetFullPath($logFile)

# Detect which governance files were changed
try {
    $changedFiles = git diff --name-only 2>$null
} catch {
    Exit 0
}

if ($null -eq $changedFiles -or $changedFiles.Count -eq 0) { Exit 0 }

# Only log changes to governance, specs, rules, or source code files
$governancePatterns = '\.claude[/\\]', 'autorag-server[/\\]app[/\\]', 'autorag-client[/\\]', 'infra[/\\]'
$relevantFiles = @($changedFiles | Where-Object {
    $f = $_
    $governancePatterns | Where-Object { $f -match $_ }
})

if ($relevantFiles.Count -eq 0) { Exit 0 }

# Build the log entry
$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm"
$fileList  = $relevantFiles | ForEach-Object { "  - ``$_``" }
$entry = @"

## $timestamp

**Files modified:**
$($fileList -join "`n")

---
"@

# Ensure log file exists with header
if (-not (Test-Path $logFile)) {
    $header = @"
# AutoRAG Architect — Session Activity Log

Auto-generated by `.claude/hooks/auto-memory-log.ps1`
Each entry records which files were modified in a Claude Code session.

---
"@
    Set-Content $logFile $header -Encoding UTF8
}

# Append the entry
Add-Content $logFile $entry -Encoding UTF8
Write-Host "Memory log updated: $($relevantFiles.Count) file(s) recorded." -ForegroundColor DarkCyan
