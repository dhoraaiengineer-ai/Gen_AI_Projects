"""Repository — pipelines table.

All DB access for the pipelines table.
No business logic — pure persistence operations only.

Pattern:
  - SQLAlchemy AsyncSession for reads (typed ORM results)
  - All queries MUST include organization_id scoping (multi-tenancy — Rule 30)
  - Soft-delete: filter WHERE deleted_at IS NULL on every list/get query
  - UUID v7 primary keys generated by the ORM model default

Team 3 owns this file.
Spec: .claude/specs/database.md § pipelines table
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from datetime import UTC, datetime
from typing import Any, cast

from sqlalchemy import CursorResult, select, update
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.pipeline import Pipeline


class PipelineRepository:
    """Data-access layer for pipelines table.

    All public methods require both pipeline_id AND organization_id to prevent
    cross-tenant data leakage. Never issue a query without the org_id filter.
    """

    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    # ── Write operations ──────────────────────────────────────────────────────

    async def create(
        self,
        *,
        organization_id: uuid.UUID,
        name: str,
        **kwargs: Any,  # noqa: ANN401
    ) -> Pipeline:
        """Insert a new pipeline row and return the ORM instance.

        Args:
            organization_id: Tenant scoping — mandatory.
            name: Human-readable pipeline name (unique per org).
            **kwargs: Optional column overrides (status, chunk_strategy, etc.).

        Returns:
            The persisted Pipeline ORM instance with server-generated id/created_at.
        """
        pipeline = Pipeline(
            organization_id=organization_id,
            name=name,
            **kwargs,
        )
        self._session.add(pipeline)
        await self._session.flush()  # get DB-generated id without committing
        await self._session.refresh(pipeline)
        return pipeline

    async def update_status(
        self,
        *,
        pipeline_id: uuid.UUID,
        organization_id: uuid.UUID,
        status: str,
    ) -> None:
        """Update pipeline status — validates org ownership first.

        Args:
            pipeline_id: Target pipeline.
            organization_id: Must match the pipeline's org (access control).
            status: New status value (pending|running|ready|failed|decommissioned).

        Raises:
            ValueError: If pipeline not found or org mismatch.
        """
        stmt = (
            update(Pipeline)
            .where(
                Pipeline.id == pipeline_id,
                Pipeline.organization_id == organization_id,
                Pipeline.deleted_at.is_(None),
            )
            .values(status=status, updated_at=datetime.now(UTC))
        )
        result = cast("CursorResult[Any]", await self._session.execute(stmt))
        if result.rowcount == 0:
            raise ValueError(
                f"Pipeline {pipeline_id} not found in org {organization_id} or already deleted."
            )

    async def update_current_version(
        self,
        *,
        pipeline_id: uuid.UUID,
        organization_id: uuid.UUID,
        current_version: int,
        chunk_strategy: str | None = None,
        embedding_model: str | None = None,
    ) -> None:
        """Persist a version bump on the pipeline row.

        20-Jul-2026 fix: PipelineService.create_version() previously computed
        `new_version` locally but never wrote it back to the DB (a repeat call
        would compute the same version number again) and never synced
        chunk_strategy/embedding_model onto the pipeline row -- both real
        bugs, fixed by giving create_version() a real place to persist them.
        chunk_strategy/embedding_model are optional so a version bump with no
        config change (the original bare `POST /versions` route) doesn't
        overwrite them with None.
        """
        values: dict[str, object] = {
            "current_version": current_version,
            "updated_at": datetime.now(UTC),
        }
        if chunk_strategy is not None:
            values["chunk_strategy"] = chunk_strategy
        if embedding_model is not None:
            values["embedding_model"] = embedding_model

        stmt = (
            update(Pipeline)
            .where(
                Pipeline.id == pipeline_id,
                Pipeline.organization_id == organization_id,
                Pipeline.deleted_at.is_(None),
            )
            .values(**values)
        )
        result = cast("CursorResult[Any]", await self._session.execute(stmt))
        if result.rowcount == 0:
            raise ValueError(
                f"Pipeline {pipeline_id} not found in org {organization_id} or already deleted."
            )

    async def update_score(
        self,
        *,
        pipeline_id: uuid.UUID,
        organization_id: uuid.UUID,
        unified_score: float,
    ) -> None:
        """Update the cached unified_score on the pipeline row.

        Called by the Evaluator agent after a completed evaluation_run.
        """
        stmt = (
            update(Pipeline)
            .where(
                Pipeline.id == pipeline_id,
                Pipeline.organization_id == organization_id,
                Pipeline.deleted_at.is_(None),
            )
            .values(
                unified_score=unified_score,
                updated_at=datetime.now(UTC),
            )
        )
        await self._session.execute(stmt)

    async def soft_delete(
        self,
        *,
        pipeline_id: uuid.UUID,
        organization_id: uuid.UUID,
    ) -> None:
        """Soft-delete a pipeline by setting deleted_at (never hard DELETE).

        The pipeline is hidden from all list/get queries after this point.
        Its rows in the shared pipeline_chunks table (Version 4.0) are NOT
        deleted here — that requires a separate cleanup job.
        """
        stmt = (
            update(Pipeline)
            .where(
                Pipeline.id == pipeline_id,
                Pipeline.organization_id == organization_id,
                Pipeline.deleted_at.is_(None),
            )
            .values(deleted_at=datetime.now(UTC))
        )
        result = cast("CursorResult[Any]", await self._session.execute(stmt))
        if result.rowcount == 0:
            raise ValueError(f"Pipeline {pipeline_id} not found or already deleted.")

    # ── Read operations ───────────────────────────────────────────────────────

    async def get_by_id(
        self,
        *,
        pipeline_id: uuid.UUID,
        organization_id: uuid.UUID,
    ) -> Pipeline | None:
        """Fetch a single pipeline by PK, org-scoped, excluding soft-deleted rows.

        Returns:
            Pipeline ORM instance or None if not found / deleted.
        """
        stmt = select(Pipeline).where(
            Pipeline.id == pipeline_id,
            Pipeline.organization_id == organization_id,
            Pipeline.deleted_at.is_(None),
        )
        result = await self._session.execute(stmt)
        return result.scalar_one_or_none()

    async def get_by_name(
        self,
        *,
        name: str,
        organization_id: uuid.UUID,
    ) -> Pipeline | None:
        """Fetch pipeline by unique (org, name) key, excluding soft-deleted rows."""
        stmt = select(Pipeline).where(
            Pipeline.name == name,
            Pipeline.organization_id == organization_id,
            Pipeline.deleted_at.is_(None),
        )
        result = await self._session.execute(stmt)
        return result.scalar_one_or_none()

    async def list_by_org(
        self,
        *,
        organization_id: uuid.UUID,
        status: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> Sequence[Pipeline]:
        """List active (non-deleted) pipelines for an org.

        Args:
            organization_id: Tenant filter — mandatory.
            status: Optional status filter (pending|running|ready|failed|decommissioned).
            limit: Page size (max 200 enforced at service layer).
            offset: Pagination offset.

        Returns:
            Ordered list of Pipeline instances (created_at DESC).
        """
        stmt = (
            select(Pipeline)
            .where(
                Pipeline.organization_id == organization_id,
                Pipeline.deleted_at.is_(None),
            )
            .order_by(Pipeline.created_at.desc())
            .limit(limit)
            .offset(offset)
        )
        if status is not None:
            stmt = stmt.where(Pipeline.status == status)

        result = await self._session.execute(stmt)
        return result.scalars().all()
