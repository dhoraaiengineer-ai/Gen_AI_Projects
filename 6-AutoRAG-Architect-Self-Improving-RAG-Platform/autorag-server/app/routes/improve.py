"""GET /api/v1/improve/{run_id} — Return Improver Agent variant config for a run."""

from __future__ import annotations

import uuid

import structlog
from fastapi import APIRouter, Depends
from sqlalchemy.ext.asyncio import AsyncSession

from app.auth.dependencies import get_current_user
from app.auth.schemas import AuthenticatedUser
from app.core.database import get_db
from app.core.dependencies import get_organization_id, get_trace_id
from app.repositories.evaluation_repository import EvaluationRepository

logger = structlog.get_logger(__name__)

router = APIRouter()


@router.get("/{run_id}")
async def get_improvement(
    run_id: str,
    db: AsyncSession = Depends(get_db),
    current_user: AuthenticatedUser = Depends(get_current_user),
    organization_id: str = Depends(get_organization_id),
    trace_id: str = Depends(get_trace_id),
) -> dict:
    """
    Returns the variant config generated by the Improver Agent for a failed run.
    variant_config contains hyperparameter changes (chunk_size, overlap, top_k, prompt)
    that the next ingestion loop will apply.
    If improvement has not yet run, variant_config will be null.
    """
    repo = EvaluationRepository(db)
    run = await repo.get_by_run_id(
        run_id=uuid.UUID(run_id),
        organization_id=uuid.UUID(organization_id),
    )
    if run is None:
        return {
            "status": "error",
            "data": None,
            "error": {"code": "RUN_NOT_FOUND", "message": f"Evaluation run {run_id} not found."},
            "request_id": trace_id,
        }

    # 12-Jul-2026 (Part E fix): variant_config/variant_id/score_delta were
    # previously read from evaluation_runs.failure_taxonomy, but that column
    # only ever holds {"error_type": ...} (guardrail block) or
    # {"failure_type", "confidence", "remediation_hint", "root_cause_analysis"}
    # (real Diagnoser classification, app/routes/evaluate.py's
    # _build_failure_taxonomy) -- Improver's output was never written there,
    # so these fields silently read null on every real run. The winner's data
    # already exists in improver_candidates -- derive from it instead.
    metadata = run.agent_execution_metadata or {}
    raw_candidates = metadata.get("improver_candidates")
    candidates: list[dict] | None = raw_candidates if isinstance(raw_candidates, list) else None
    winner = next((c for c in candidates if c.get("is_winner")), None) if candidates else None

    variant_config = winner.get("config") if winner else None
    variant_id = winner.get("variant_id") if winner else None
    score_delta = winner.get("score_delta") if winner else None
    improvement_attempt = metadata.get("improvement_attempt", 0)

    # score_type is "estimated" not "measured": the Improver's per-candidate
    # unified_score is a deterministic heuristic (_SCORE_DELTA_ESTIMATES), not
    # a live re-evaluation of that config — see METRICS_WIRING_MATRIX.md.
    candidates_out = (
        [
            {
                "candidate_id": c.get("variant_id"),
                "config": c.get("config"),
                "score": c.get("unified_score"),
                "score_type": "estimated",
                "score_delta": c.get("score_delta"),
                "selected": bool(c.get("is_winner")),
                "mlflow_run_id": c.get("mlflow_run_id"),
            }
            for c in candidates
        ]
        if candidates is not None
        else None
    )

    return {
        "status": "ok",
        "data": {
            "run_id": run_id,
            "pipeline_id": str(run.pipeline_id),
            "status": run.status,
            "current_score": float(run.unified_score) if run.unified_score is not None else None,
            "variant_id": variant_id,
            "variant_config": variant_config,
            "improvement_attempt": improvement_attempt,
            "score_delta": score_delta,
            "candidates": candidates_out,  # null when Improver never ran for this run
            "message": (
                "Variant config ready — will be applied on next ingestion loop."
                if variant_config
                else "Improver has not yet run for this evaluation run."
            ),
        },
        "error": None,
        "request_id": trace_id,
    }
