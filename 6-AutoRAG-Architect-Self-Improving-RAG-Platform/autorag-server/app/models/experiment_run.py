"""ORM model — experiment_runs table (Improver Agent variants + MLflow tracking).

Mirrors migrations 0002 (table + ck_experiment_runs_status) and 0003
(indexes, incl. GIN on variant_config). variant_config is NOT NULL — every
experiment records the hyperparameter variant it evaluated.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Numeric,
    String,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base, uuid7


class ExperimentRun(Base):
    __tablename__ = "experiment_runs"
    __table_args__ = (
        CheckConstraint(
            "status IN ('pending','running','completed','failed')",
            name="ck_experiment_runs_status",
        ),
        Index("ix_experiment_runs_pipeline_id", "pipeline_id"),
        Index("ix_experiment_runs_organization_id", "organization_id"),
        Index(
            "ix_experiment_runs_parent_evaluation_run_id", "parent_evaluation_run_id"
        ),
        Index("ix_experiment_runs_status", "status"),
        Index("ix_experiment_runs_created_at", "created_at"),
        Index(
            "ix_experiment_runs_variant_config_gin",
            "variant_config",
            postgresql_using="gin",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid7)
    pipeline_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("pipelines.id", ondelete="CASCADE"), nullable=False
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), nullable=False
    )
    # The evaluation run that triggered the Improver Agent
    parent_evaluation_run_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("evaluation_runs.id", ondelete="SET NULL"), nullable=True
    )
    # The pipeline version produced by applying this variant (if promoted)
    result_pipeline_version_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("pipeline_versions.id", ondelete="SET NULL"), nullable=True
    )
    # The evaluation run that scored the resulting version (migration 0015,
    # 20-Jul-2026, Apply Improvement) -- lets callers pull latency_p95_ms/
    # cost_usd/recall per version from evaluation_runs, the only table that
    # carries them.
    result_evaluation_run_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("evaluation_runs.id", ondelete="SET NULL"), nullable=True
    )

    # MLflow cross-reference
    mlflow_run_id: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Hyperparameter variant (generated by Improver Agent)
    variant_config: Mapped[dict] = mapped_column(JSONB, nullable=False)
    # e.g. {"chunk_size": 512, "chunk_overlap": 64, "k_value": 10, "strategy": "hierarchical"}

    # Scores for this variant
    unified_score: Mapped[float | None] = mapped_column(Numeric(4, 3), nullable=True)
    score_delta: Mapped[float | None] = mapped_column(Numeric(4, 3), nullable=True)
    # score_delta = this_score - parent_score (positive = improvement)

    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        server_default="pending",
        # values: pending | running | completed | failed
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    def __repr__(self) -> str:
        return f"<ExperimentRun id={self.id} score={self.unified_score} delta={self.score_delta}>"
